#!/bin/bash
# Builds the capture image local/glm53-v091-p3b-capture:local from the LOCAL stock 0.9.1 image (a9e985c0), CPU only:
# `docker build --network none --pull=false`; every check container is `docker run --rm --network none` with
# CUDA_VISIBLE_DEVICES= (no --gpus).  Never retags or removes any existing image.
#   1. make_hooked.py --check   hooked files == regenerated from the stock copies; additive gate (insertions only,
#                               every inserted line marked "local-p3b", exact counts)
#   2. Dockerfile.p3b           generated from the template below with the current file hashes (kept as a record);
#                               in-build gates: stock hashes before COPY, hooked hashes after, py_compile, marker counts,
#                               module inert without GLM53_P3B
#   3. post-build gates         (a) of all vllm/*.py in the image, only the 3 expected files differ from the stock
#                               image (new p3b_capture_hooks.py, hooked exl3.py, hooked b12x_mla_sparse.py);
#                               (b) CPU import of the hooked modules with GLM53_P3B unset (inert) and =capture
#                               (install() wraps the 3 runner methods and the 2 graph run methods)
# Output: build-p3b.log, image-id.txt, image-vllm-py.sha256, stock-vllm-py.sha256, post-build-gates.txt
set -u
cd "$(dirname "$0")" || exit 2
BASE=ghcr.io/tpurtell/glm-5.3-flash-exl3-4bpw-2x-rtx@sha256:a9e985c09885710601b32ac86e81256aa1279b542caa345233ce331a816d7e07
TAG=local/glm53-v091-p3b-capture:local
VP=/usr/local/lib/python3.12/dist-packages/vllm
case "$TAG" in local/glm53-v091-p3b-*:local) ;; *) echo "REFUSED: tag outside local/glm53-v091-p3b-*:local"; exit 2;; esac
docker image inspect "$BASE" >/dev/null 2>&1 || { echo "ABORT: base image missing locally (no pulls)"; exit 3; }
python3 make_hooked.py --check || { echo "ABORT: hooked files fail the additive gate"; exit 4; }

H_MOD=$(sha256sum files/vllm/p3b_capture_hooks.py | cut -d' ' -f1)
H_EXL3=$(sha256sum files/vllm/model_executor/layers/quantization/exl3.py | cut -d' ' -f1)
H_MLA=$(sha256sum files/vllm/v1/attention/backends/mla/b12x_mla_sparse.py | cut -d' ' -f1)
cat > Dockerfile.p3b <<EOF
# GENERATED by make_build.sh (do not edit): stock tpurtell 0.9.1 + local-p3b observe-only capture hooks.
# Inert unless GLM53_P3B=capture.  Built with --network none --pull=false from the local base image.
FROM ${BASE}
ARG VP=${VP}
# Gate 0: the files replaced are the stock 0.9.1 files; no capture module present.
RUN printf '%s\n' \\
    "3b4ca47cb1168bffebcfe3cf1db48daf86691c140cbf40f9c1f3aa6ad6a444d9  \${VP}/model_executor/layers/quantization/exl3.py" \\
    "6e74c42cf4385bb0451243098ec8b4a84005675fa776169fddb2fb230bab0157  \${VP}/v1/attention/backends/mla/b12x_mla_sparse.py" \\
  | sha256sum -c - && ! test -e \${VP}/p3b_capture_hooks.py
COPY files/vllm/p3b_capture_hooks.py \${VP}/p3b_capture_hooks.py
COPY files/vllm/model_executor/layers/quantization/exl3.py \${VP}/model_executor/layers/quantization/exl3.py
COPY files/vllm/v1/attention/backends/mla/b12x_mla_sparse.py \${VP}/v1/attention/backends/mla/b12x_mla_sparse.py
RUN printf '%s\n' \\
    "${H_MOD}  \${VP}/p3b_capture_hooks.py" \\
    "${H_EXL3}  \${VP}/model_executor/layers/quantization/exl3.py" \\
    "${H_MLA}  \${VP}/v1/attention/backends/mla/b12x_mla_sparse.py" \\
  | sha256sum -c - \\
 && python3 -m py_compile \${VP}/p3b_capture_hooks.py \${VP}/model_executor/layers/quantization/exl3.py \${VP}/v1/attention/backends/mla/b12x_mla_sparse.py \\
 && test "\$(grep -c "local-p3b" \${VP}/model_executor/layers/quantization/exl3.py)" = 13 \\
 && test "\$(grep -c "local-p3b" \${VP}/v1/attention/backends/mla/b12x_mla_sparse.py)" = 20 \\
 && CUDA_VISIBLE_DEVICES= python3 -c "import importlib.util as u; s=u.spec_from_file_location('m','\${VP}/p3b_capture_hooks.py'); m=u.module_from_spec(s); s.loader.exec_module(m); assert not m.ENABLED"
LABEL io.local.base="stock tpurtell 0.9.1 sha256:a9e985c0" io.local.purpose="captured-p3b: observe-only graph-safe capture of MoE and sparse-MLA inputs/outputs (inert unless GLM53_P3B=capture)"
EOF

docker build --network none --pull=false -f Dockerfile.p3b -t "$TAG" . > build-p3b.log 2>&1
rc=$?; echo "build rc=$rc"
[ $rc = 0 ] || { tail -20 build-p3b.log; exit 5; }
docker image inspect "$TAG" --format '{{.Id}}' > image-id.txt && cat image-id.txt

{
  echo "== post-build gates $(date -u +%FT%TZ) image $(cat image-id.txt)"
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= --entrypoint sh "$TAG" -c "cd $VP && find . -name '*.py' | sort | xargs sha256sum" > image-vllm-py.sha256
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= --entrypoint sh "$BASE" -c "cd $VP && find . -name '*.py' | sort | xargs sha256sum" > stock-vllm-py.sha256
  echo "vllm .py files: image $(wc -l < image-vllm-py.sha256), stock $(wc -l < stock-vllm-py.sha256)"
  DIFF=$(diff <(sort -k2 stock-vllm-py.sha256) <(sort -k2 image-vllm-py.sha256) | grep '^[<>]' | awk '{print $3}' | sort -u | tr '\n' ' ')
  echo "files differing from stock: $DIFF"
  EXP="./p3b_capture_hooks.py ./model_executor/layers/quantization/exl3.py ./v1/attention/backends/mla/b12x_mla_sparse.py "
  if [ "$DIFF" = "$EXP" ]; then echo "PASS gate (a): only the 3 expected files differ"; else echo "FAIL gate (a)"; fi
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= --entrypoint python3 "$TAG" -c "
import vllm.p3b_capture_hooks as m
import vllm.model_executor.layers.quantization.exl3 as e
import vllm.v1.attention.backends.mla.b12x_mla_sparse as b
import vllm.v1.worker.gpu.model_runner as mr
assert not m.ENABLED and not e._P3B_ON and not b._P3B_ON
assert not getattr(mr.GPUModelRunner, '_local_p3b', False)
print('PASS gate (b1): GLM53_P3B unset -> module inert, hooks off, runner not wrapped')
" 2>&1 | grep -E "^(PASS|FAIL)|Traceback|AssertionError"
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= -e GLM53_P3B=capture -e GLM53_P3B_DIR=/tmp/p3b --entrypoint python3 "$TAG" -c "
import vllm.p3b_capture_hooks as m
import vllm.model_executor.layers.quantization.exl3 as e
import vllm.v1.attention.backends.mla.b12x_mla_sparse as b
import vllm.v1.worker.gpu.model_runner as mr, vllm.v1.worker.gpu.cudagraph_utils as cg
assert m.ENABLED and e._P3B_ON and b._P3B_ON and mr.GPUModelRunner._local_p3b
names = [f.__qualname__ for f in (mr.GPUModelRunner.initialize_kv_cache, mr.GPUModelRunner.execute_model, mr.GPUModelRunner.prepare_attn, cg.CudaGraphManager.run_fullgraph, cg.CudaGraphManager.run_pw_graph, cg.ModelCudaGraphManager.run_fullgraph)]
assert all('install.<locals>' in n for n in names), names
assert m.S.meta is None   # nothing allocated before a runner registers
print('PASS gate (b2): GLM53_P3B=capture -> install() wrapped', len(names), 'methods; no device state before registration')
" 2>&1 | grep -E "^(PASS|FAIL)|Traceback|AssertionError"
} 2>&1 | tee post-build-gates.txt
grep -qE "^FAIL|Traceback|AssertionError" post-build-gates.txt && exit 6
exit 0
