def load_p3(path):
    sha = hashlib.sha256(open(path, "rb").read()).hexdigest()
    if sha != P3_HARNESS_SHA256:
        raise SystemExit(f"P3 harness sha256 {sha} != pinned {P3_HARNESS_SHA256}")
    spec = importlib.util.spec_from_file_location("moe_plan_eq", path)
    m = importlib.util.module_from_spec(spec)
    sys.modules["moe_plan_eq"] = m
    spec.loader.exec_module(m)
    return m


def ids_dtype(torch, cl, L, m):
    s = cl["sites"].get(("moe", L, m))
    name = (s or {}).get("ids", [None, "torch.int64"])[1]
    return getattr(torch, str(name).split(".")[-1])


class Ctx:
    def __init__(self, args, P, torch, doc, cl):
        self.args, self.P, self.torch, self.doc, self.cl = args, P, torch, doc, cl
        self.dry = args.dry
        self.dev = torch.device("cpu" if self.dry else "cuda:0")
        self.eng = None
        self.slice = P.ENGINES[args.engine]["own"]

    def plan_out(self, method, layer, rt, which, x, w, ids, launch_log=None):
        """final (bf16) and raw outputs of one plan; decode accepts m > 32 in <= 32-row chunks."""
        P, torch = self.P, self.torch
        if self.dry:
            m = int(x.shape[0])
            if which == "decode" and m > P.DECODE_CHUNK:
                parts = [P.dry_kernel(torch, self.slice, "decode", x[s:s + 32], w[s:s + 32], ids[s:s + 32], row_offset=s)
                         for s in range(0, m, 32)]
                return torch.cat([a for a, _ in parts]), torch.cat([b for _, b in parts])
            kind = which
            if kind == "forced":   # dry model of the prediction: the forced tile computes as the prefill tile
                kind = "decode" if os.environ.get("P3B_DRY_FORCED_DIFF") == "1" else "prefill"
            return P.dry_kernel(torch, self.slice, kind, x, w, ids)
        if which == "decode":
            return self.eng.run_decode_any(method, layer, rt, x, w, ids, launch_log)
        if which == "forced":
            return self.eng.run_decode_any(method, layer, rt, x, w, ids, launch_log)
        return self.eng.run_plan(method, layer, rt, "prefill", x, w, ids, launch_log)


def tensors(ctx, d, L):
    torch = ctx.torch
    hdr = d["hdr"]
    m = int(hdr[rc.H_M])
    n_real = int(min(max(int(hdr[rc.H_NTOK]), 0), m))
    x = rc.bf16(torch, d["x"][:m]).contiguous().to(ctx.dev)
    ids = torch.from_numpy(d["ids"][:m].copy()).to(ids_dtype(torch, ctx.cl, L, m)).contiguous().to(ctx.dev)
    w = torch.from_numpy(d["w"][:m].copy()).float().contiguous().to(ctx.dev)
    served = rc.bf16(torch, d["out"][:m]).contiguous().to(ctx.dev)
    return m, n_real, x, ids, w, served


def run_layer(ctx, L, ldoc, dl):
    P, torch, eng = ctx.P, ctx.torch, ctx.eng
    entries = rc.list_entries(ctx.args.cap, "moe", L)
    ldoc["n_entries_on_disk"] = len(entries)
    if not entries:
        ldoc["error"] = "no captured entries"
        return None
    if ctx.dry:
        method = layer = rt = None
        ldoc["build"] = dict(dry=True)
    else:
        t0 = time.time()
        method, layer, info = eng.build_layer(ctx.slice, L)
        eng.prepare_layer(method, layer, info)
        ldoc["build"] = info
        _, _, x0, ids0, _, _ = tensors(ctx, rc.load_npz(entries[0][1]), L)
        rt = eng.runtime(method, layer, x0, ids0, "default")
        ldoc["runtime"] = rt["meta"]
        rt = rt["rt"]
        ldoc["t_build_s"] = round(time.time() - t0, 2)
    launch = ldoc.setdefault("launch_map", {})
    traffic32 = []
    for seq, path in entries:
        if dl.passed():
            ctx.doc["stopped_reason"] = "soft deadline"
            break
        d = rc.load_npz(path, ctx.cl, "moe", L, seq)
        m, n_real, x, ids, w, served = tensors(ctx, d, L)
        real = list(range(n_real))
        allrows = list(range(m))
        e = dict(seq=seq, phase=d.get("_phase"), m=m, n_real=n_real, sha_ok=d.get("_sha_ok"),
                 bound=ctx.cl["binds"].get((L, m), {}).get("plan"))
        try:
            if ctx.args.engine == "v091":
                plan_rec = e["bound"] or ("decode" if m <= 32 else "prefill")
                b1, _ = ctx.plan_out(method, layer, rt, plan_rec, x, w, ids, launch)
                b2, _ = ctx.plan_out(method, layer, rt, plan_rec, x, w, ids, launch)
                cmp_all = P.compare(torch, b1, served, allrows)
                e["baseline"] = dict(plan=plan_rec, bound_record=e["bound"] is not None,
                                     bitequal_all_rows=cmp_all["n_rows_differ"] == 0,
                                     bitequal_real_rows=P.compare(torch, b1, served, real)["n_rows_differ"] == 0 if real else None,
                                     n_rows_differ=cmp_all["n_rows_differ"], max_abs=cmp_all["max_abs"],
                                     repeat_bitequal=P.compare(torch, b1, b2, allrows)["n_rows_differ"] == 0)
                if not ctx.dry:
                    app = eng.run_apply(method, layer, x, w, ids)
                    e["baseline"]["apply_bitequal_served"] = P.compare(torch, app, served, allrows)["n_rows_differ"] == 0
            dec = [ctx.plan_out(method, layer, rt, "decode", x, w, ids, launch) for _ in range(2)]
            pre = [ctx.plan_out(method, layer, rt, "prefill", x, w, ids, launch) for _ in range(2)]
            e["within"] = dict(decode=P.within(torch, [a for a, _ in dec], real),
                               prefill=P.within(torch, [a for a, _ in pre], real))
            e["between"] = P.compare(torch, dec[0][0], pre[0][0], real)
            if dec[0][1].dtype == torch.float32 and pre[0][1].dtype == torch.float32:
                e["between_raw_fp32"] = P.compare(torch, dec[0][1], pre[0][1], real)
            e["digests_decode"] = P.row_digests(torch, dec[0][0][:n_real])
            if d.get("_phase") == "traffic" and m == 32 and n_real >= 24:
                traffic32.append((seq, x[:n_real], w[:n_real], ids[:n_real], dec[0][0][:n_real]))
        except Exception as exc:  # noqa: BLE001
            e["error"] = repr(exc)[:300]
            e["tb"] = traceback.format_exc()[-800:]
        ldoc["entries"].append(e)
    # composed batches (labelled; not a served shape on 0.9.1 at 8 in flight)
    comp = ldoc.setdefault("composed", [])
    for k in range(0, len(traffic32) - 1, 2):
        if dl.passed():
            break
        a, b = traffic32[k], traffic32[k + 1]
        for extra in (8, 16):
            n_b = min(extra, a[1].shape[0], b[1].shape[0])
            x = torch.cat([a[1][:32], b[1][:n_b]])
            w = torch.cat([a[2][:32], b[2][:n_b]])
            ids = torch.cat([a[3][:32], b[3][:n_b]])
            mm = int(x.shape[0])
            rows = list(range(mm))
            dd, _ = ctx.plan_out(method, layer, rt, "decode", x, w, ids, launch)
            pp, _ = ctx.plan_out(method, layer, rt, "prefill", x, w, ids, launch)
            first = a[4].shape[0]
            comp.append(dict(seqs=[a[0], b[0]], m=mm, between=P.compare(torch, dd, pp, rows),
                             decode_chunk_rows_equal_served_shape=P.compare(
                                 torch, dd[:min(32, first)], a[4][:min(32, first)],
                                 list(range(min(32, first))))["n_rows_differ"] == 0))
    # positive control on the first traffic m = 32 entry
    if traffic32 and not dl.passed():
        seq, x, w, ids, _ = traffic32[0]
        x2 = x.clone()
        ch = int(x2[0].float().abs().argmax())
        x2.view(torch.int16)[0, ch] += 1
        res = {}
        for which in ("decode", "prefill"):
            o1, _ = ctx.plan_out(method, layer, rt, which, x, w, ids)
            o2, _ = ctx.plan_out(method, layer, rt, which, x2, w, ids)
            c = P.compare(torch, o1, o2, list(range(x.shape[0])))
            res[which] = dict(rows_changed=c["rows_differ"], ok=c["rows_differ"] == [0])
        ldoc["control_ulp"] = dict(seq=seq, **res, ok=all(v["ok"] for v in res.values()))
    return method, layer, rt


def summarize_layer(ldoc, engine):
    es = [e for e in ldoc["entries"] if "error" not in e]
    out = dict(entries=len(ldoc["entries"]), errors=len(ldoc["entries"]) - len(es), by_m={})
    if engine == "v091":
        bl = [e["baseline"] for e in es if "baseline" in e]
        out["baseline_all_bitequal"] = all(b["bitequal_all_rows"] for b in bl) if bl else None
        out["baseline_not_reproduced"] = sum(1 for b in bl if not b["bitequal_all_rows"])
        out["baseline_without_bind_record"] = sum(1 for b in bl if not b["bound_record"])
    out["within_all_bitequal"] = all(e["within"]["decode"]["bitequal"] and e["within"]["prefill"]["bitequal"] for e in es)
    for e in es:
        k = f"{e['phase']}/m{e['m']}"
        b = out["by_m"].setdefault(k, dict(entries=0, rows=0, rows_differ=0, rel_l2=[], max_abs=0.0, fp32_rel_l2=[]))
        b["entries"] += 1
        b["rows"] += e["between"].get("rows", 0)
        b["rows_differ"] += e["between"].get("n_rows_differ", 0)
        if e["between"].get("n_rows_differ"):
            b["rel_l2"].append(e["between"]["rel_l2"])
            if "between_raw_fp32" in e:
                b["fp32_rel_l2"].append(e["between_raw_fp32"]["rel_l2"])
        b["max_abs"] = max(b["max_abs"], e["between"].get("max_abs", 0.0))
    for b in out["by_m"].values():
        rl, fl = b.pop("rel_l2"), b.pop("fp32_rel_l2")
        b["rel_l2_median"], b["rel_l2_max"] = rc.median(rl), max(rl) if rl else None
        b["fp32_rel_l2_median"] = rc.median(fl)
        b["row_differ_frac"] = round(b["rows_differ"] / b["rows"], 4) if b["rows"] else None
    deficits = []
    for m, need in MOE_MIN.items():
        have = sum(1 for e in es if e["phase"] == "traffic" and e["m"] == m)
        if have < need:
            deficits.append(f"m={m}: {have} < {need}")
    small = sum(1 for e in es if e["phase"] == "traffic" and e["m"] <= 8)
    if small < MOE_MIN_SMALL:
        deficits.append(f"m<=8: {small} < {MOE_MIN_SMALL}")
    out["coverage_deficits"] = deficits
    ctl = ldoc.get("control_ulp", {}).get("ok")
    if deficits or out["errors"] or ctl is False or (engine == "v091" and out.get("baseline_all_bitequal") is False):
        v = "INCOMPLETE" if (deficits or out["errors"] or ctl is False) else "BASELINE NOT REPRODUCED"
    else:
        diff = any(b["rows_differ"] for k, b in out["by_m"].items())
        v = "DIFFERENCES (characterize)" if diff else "EQUAL ON CAPTURED ROWS"
    out["verdict"] = v
    return out


# ---------------------------------------------------------------- forced-tile confirmation
def forced_layer(ctx, L):
    """Build layer L again through the image code with the weight plan's tile forced to FORCED."""
    eng, exl3 = ctx.eng, ctx.eng.exl3
    real_loader = exl3._load_b12x_fused_moe
    real = real_loader()
    seen = {}

    def plan_weights(**kw):
        seen["tile_config_in"] = kw.get("trellis_tile_config")
        if kw.get("trellis_tile_config") is None:
            kw["trellis_tile_config"] = FORCED
        seen["tile_config_passed"] = kw["trellis_tile_config"]
        return real.plan_weights(**kw)

    proxy = SimpleNamespace(**vars(real))
    proxy.plan_weights = plan_weights
    method, layer, info = eng.build_layer(ctx.slice, L)
    exl3._load_b12x_fused_moe = lambda: proxy
    try:
        eng.prepare_layer(method, layer, info)
    finally:
        exl3._load_b12x_fused_moe = real_loader
    layer.exl3_trellis_tile_config = FORCED
    wp = getattr(layer.exl3_trellis_weights, "plan", None)
    seen["weight_plan_tile"] = getattr(wp, "trellis_tile_config", None)
    return method, layer, seen


def run_forced(ctx, layers_done, p3doc, dl):
    """layers_done: {L: (method, layer, rt)} stock objects (rt = default runtime with the prefill plan)."""
    P, torch, eng = ctx.P, ctx.torch, ctx.eng
    sec = dict(label="forced-tile confirmation", forced=list(FORCED), prediction="forced decode == stock prefill, bit for bit",
               layers={})
    for L, (method, layer, rt) in layers_done.items():
        if dl.passed():
            sec["stopped_reason"] = "soft deadline"
            break
        ld = sec["layers"][str(L)] = dict(captured=[], p3_fixtures=[], launch_map={})
        try:
            if ctx.dry:
                fm = fl = frt = None
                ld["forcing"] = dict(dry=True)
            else:
                t0 = time.time()
                fm, fl, seen = forced_layer(ctx, L)
                ld["forcing"] = dict({k: (list(v) if isinstance(v, tuple) else v) for k, v in seen.items()},
                                     t_build_s=round(time.time() - t0, 2))
                entries = rc.list_entries(ctx.args.cap, "moe", L)
                _, _, x0, ids0, _, _ = tensors(ctx, rc.load_npz(entries[0][1]), L)
                t1 = time.time()
                frt_d = eng.runtime(fm, fl, x0, ids0, "forced_tile", env={"VLLM_EXL3_PREFILL_TRELLIS": "0"})
                frt = frt_d["rt"]
                ld["runtime"] = dict(frt_d["meta"], t_plan_compile_s=round(time.time() - t1, 2))
            # captured rows m = 16..32
            for seq, path in rc.list_entries(ctx.args.cap, "moe", L):
                if dl.passed():
                    break
                d = rc.load_npz(path, ctx.cl, "moe", L, seq)
                m, n_real, x, ids, w, served = tensors(ctx, d, L)
                if not 16 <= m <= 32 or n_real == 0:
                    continue
                real = list(range(n_real))
                f, _ = ctx.plan_out(fm, fl, frt, "forced", x, w, ids, ld["launch_map"])
                pre, _ = ctx.plan_out(method, layer, rt, "prefill", x, w, ids)
                dec, _ = ctx.plan_out(method, layer, rt, "decode", x, w, ids)
                c = P.compare(torch, f, pre, real)
                ld["captured"].append(dict(seq=seq, phase=d.get("_phase"), m=m, rows=len(real),
                                           forced_vs_prefill_bitequal=c["n_rows_differ"] == 0,
                                           n_rows_differ=c["n_rows_differ"], max_abs=c["max_abs"], rel_l2=c["rel_l2"],
                                           forced_vs_stock_decode_rows_differ=P.compare(torch, f, dec, real)["n_rows_differ"]))
            # P3 synthetic m = 16 / 32 fixtures (x1, uniform, seed 0, 3 concentrations)
            ref = eng.ref_rms(L) if eng is not None else 1.0     # dry --dry-skip-weights: no model, digests differ
            p3fx = {}
            if p3doc:
                for f in p3doc["slices"]["tp2r0"]["layers"][str(L)]["fixtures"]:
                    p3fx[f["id"]] = f
            for m in (16, 32):
                for conc in P.CONCS:
                    fdesc = dict(layer=L, m=m, scale="x1", conc=conc, wmode="uniform", seed=0, kind="main")
                    fid = P.fixture_id(fdesc)
                    fx = P.make_fixture(torch, fdesc, ref)
                    x, w = fx["x"].to(ctx.dev), fx["w"].to(ctx.dev)
                    ids = fx["ids"].to(ids_dtype(torch, ctx.cl, L, m)).to(ctx.dev)
                    rows = list(range(m))
                    f, _ = ctx.plan_out(fm, fl, frt, "forced", x, w, ids, ld["launch_map"])
                    pre, _ = ctx.plan_out(method, layer, rt, "prefill", x, w, ids)
                    c = P.compare(torch, f, pre, rows)
                    p3 = p3fx.get(fid)
                    ld["p3_fixtures"].append(dict(
                        id=fid, input_digest=fx["digest"], p3_input_digest_match=(p3 or {}).get("input_digest") == fx["digest"] if p3 else None,
                        forced_vs_prefill_bitequal=c["n_rows_differ"] == 0, n_rows_differ=c["n_rows_differ"],
                        max_abs=c["max_abs"],
                        prefill_digests_match_p3=(P.row_digests(torch, pre) == (p3 or {}).get("digests", {}).get("prefill")) if p3 else None))
            lm = ld["launch_map"]
            eff = [v for k, v in lm.items() if k.startswith("decode:m") and 16 <= int(k.split("m")[-1]) <= 32]
            ld["forcing_effective"] = (bool(eff) and all(v.get("fc1_tile_k") == 64 and v.get("fc1_tile_n") == 256 and
                                                         v.get("fc2_tile_k") == 64 and v.get("fc2_tile_n") == 256
                                                         for v in eff)) if not ctx.dry else None
            allc = ld["captured"] + ld["p3_fixtures"]
            ld["n_compared"] = len(allc)
            ld["all_bitequal"] = bool(allc) and all(c["forced_vs_prefill_bitequal"] for c in allc)
        except Exception as exc:  # noqa: BLE001
            ld["error"] = repr(exc)[:300]
            ld["tb"] = traceback.format_exc()[-1000:]
    lays = list(sec["layers"].values())
    if not lays or any("error" in v for v in lays) or sec.get("stopped_reason"):
        sec["verdict"] = "INCOMPLETE"
    elif any(v.get("forcing_effective") is False for v in lays):
        sec["verdict"] = "FORCING NOT EFFECTIVE (no conclusion)"
    else:
        sec["verdict"] = ("PREDICTION HOLDS (bit-equal on all compared rows)" if all(v["all_bitequal"] for v in lays)
                          else "PREDICTION FAILS (forced decode differs from prefill)")
    return sec


def dry_forced_probe(ctx):
    """CPU: the forcing path through the image code up to api.prepare_weights, and the image's tile rule."""
    eng, exl3 = ctx.eng, ctx.eng.exl3
    out = {}
    real_loader = exl3._load_b12x_fused_moe
    real = real_loader()
    seen = {}

    class Stop(Exception):
        pass

    def plan_weights(**kw):
        seen["tile_config_in"] = kw.get("trellis_tile_config")
        if kw.get("trellis_tile_config") is None:
            kw["trellis_tile_config"] = FORCED
        p = real.plan_weights(**kw)
        seen["weight_plan_tile"] = getattr(p, "trellis_tile_config", None)
        return p

    def prepare_weights(**kw):
        raise Stop()

    proxy = SimpleNamespace(**vars(real))
    proxy.plan_weights = plan_weights
    proxy.prepare_weights = prepare_weights
    method, layer, info = eng.build_layer(ctx.slice, 3)
    exl3._load_b12x_fused_moe = lambda: proxy
    try:
        method.process_weights_after_loading(layer)
        out["reached"] = "complete (unexpected on CPU)"
    except Stop:
        out["reached"] = "api.prepare_weights (CUDA required beyond)"
    except Exception as exc:  # noqa: BLE001
        out["reached"] = "error"
        out["error"] = repr(exc)[:300]
    finally:
        exl3._load_b12x_fused_moe = real_loader
    out["tile_config_in"] = seen.get("tile_config_in")
    out["weight_plan_tile"] = list(seen["weight_plan_tile"]) if seen.get("weight_plan_tile") else None
    from b12x.moe.fused_moe import _impl as FI
    rule = {}
    for cfg_name, cfg in (("stock(None)", None), ("forced", FORCED)):
        rule[cfg_name] = {m: list(FI._projection_mixed_tile_config(cfg, hidden_size=4096, intermediate_size=1024,
                                                                    token_count=m, direct_topk_routes=False))
                          for m in (1, 8, 9, 10, 16, 24, 32, 1024)}
    out["tile_rule"] = rule
    out["ok"] = (out["reached"].startswith("api.prepare_weights") and out["tile_config_in"] is None
                 and out["weight_plan_tile"] == list(FORCED)
                 and all(v == [128, 128, 128, 128] for m, v in rule["stock(None)"].items() if 10 <= m <= 32)
                 and all(v == list(FORCED) for v in rule["forced"].values()))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", required=True, choices=("v091", "v070"))
    ap.add_argument("--cap", required=True)
    ap.add_argument("--caplog", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--p3-harness", default="/p3h/moe_plan_eq.py")
    ap.add_argument("--p3-json", default=None)
    ap.add_argument("--model-dir", default="/model-repo/snapshots/0490d2f708b12145f6516555ab066aaeb401cd21")
    ap.add_argument("--dry", action="store_true")
    ap.add_argument("--dry-skip-weights", action="store_true")
    ap.add_argument("--dry-forced-probe", action="store_true")
    ap.add_argument("--forced-tile", action="store_true")
    ap.add_argument("--deadline-s", type=float, default=None)
    ap.add_argument("--layers", default=",".join(map(str, LAYERS)))
    args = ap.parse_args()
    if not args.dry and os.environ.get("P3B_DRY_FORCED_DIFF"):
        print("REFUSED: dry-test switch set outside --dry")
        return 2
    os.umask(0o077)
    import torch
    P = load_p3(args.p3_harness)
    dl = rc.Deadline(args.deadline_s)
    doc = dict(schema=SCHEMA, engine=args.engine, mode="dry" if args.dry else "gpu", status="running",
               p3_harness_sha256=P3_HARNESS_SHA256, layers={}, errors=[], timings={})
    rc.write_json(args.out, doc)
    try:
        cl = rc.load_caplog(args.caplog)
        ctx = Ctx(args, P, torch, doc, cl)
        if args.engine == "v070" and args.forced_tile:
            raise SystemExit("--forced-tile is a v091 check")
        need_engine = not (args.dry and args.dry_skip_weights and not args.dry_forced_probe)
        if need_engine:
            ctx.eng = P.Engine(SimpleNamespace(dry=args.dry, model_dir=args.model_dir), doc)
            doc["exl3_sha256_matches_engine"] = P.sha256_file(P.REUSED_FILES[0]) == P.ENGINES[args.engine]["exl3_sha256"]
            if not doc["exl3_sha256_matches_engine"]:
                raise SystemExit("exl3.py does not match the engine: wrong image")
            if not args.dry:
                env_mm = {k: (os.environ.get(k), v) for k, v in P.SERVED_ENV.items() if os.environ.get(k) != v}
                doc["env_matches_served"] = not env_mm
                if env_mm:
                    raise SystemExit(f"served env not set: {env_mm}")
        if args.dry and args.dry_forced_probe:
            doc["dry_forced_probe"] = dry_forced_probe(ctx)
        done = {}
        t0 = time.time()
        for L in [int(v) for v in args.layers.split(",")]:
            if dl.passed():
                doc["stopped_reason"] = "soft deadline"
                break
            ldoc = doc["layers"][str(L)] = dict(entries=[])
            res = run_layer(ctx, L, ldoc, dl)
            if res is not None:
                done[L] = res
            ldoc["summary"] = summarize_layer(ldoc, args.engine)
            rc.write_json(args.out, doc)
        doc["timings"]["layers_s"] = round(time.time() - t0, 1)
        if args.forced_tile:
            t1 = time.time()
            p3doc = json.load(open(args.p3_json)) if args.p3_json and os.path.exists(args.p3_json) else None
            doc["forced_tile_confirmation"] = run_forced(ctx, done, p3doc, dl)
            doc["timings"]["forced_s"] = round(time.time() - t1, 1)
        errs = [f"L{k}: {v['summary'].get('errors')}" for k, v in doc["layers"].items()
                if v.get("summary", {}).get("errors")]
        doc["status"] = "partial" if doc.get("stopped_reason") else ("error" if errs else "complete")
    except SystemExit as exc:
        doc["status"] = "error"
        doc["errors"].append(str(exc))
    except Exception as exc:  # noqa: BLE001
        doc["status"] = "error"
        doc["errors"].append(dict(error=repr(exc)[:400], tb=traceback.format_exc()[-1500:]))
    doc["finished"] = time.time()
    rc.write_json(args.out, doc)
    print(json.dumps(dict(part="moe", engine=args.engine, status=doc["status"],
                          verdicts={k: v.get("summary", {}).get("verdict") for k, v in doc["layers"].items()},
                          forced=(doc.get("forced_tile_confirmation") or {}).get("verdict"),
                          dry_forced_probe=(doc.get("dry_forced_probe") or {}).get("ok"))))
    return 0 if doc["status"] == "complete" else (4 if doc["status"] == "partial" else 5)


if __name__ == "__main__":
    sys.exit(main())
