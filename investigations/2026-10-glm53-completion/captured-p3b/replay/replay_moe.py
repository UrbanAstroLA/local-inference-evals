#!/usr/bin/env python3
"""captured-p3b, step B(1): MoE plan replay on captured served rows (one GPU; stock images by digest).

usage: replay_moe.py --engine v091|v070 --cap CAPDIR --caplog CAPLOGDIR --out OUT.json [--dry] [--deadline-s N]
                     [--forced-tile] [--p3-json P3_V091_JSON] [--model-dir DIR] [--dry-skip-weights]
                     [--dry-forced-probe]

Reuses the P3 Stage 1 harness (moe-plan-p3/harness/moe_plan_eq.py, sha256 pinned below, imported read-only):
the image's own EXL3 code builds each engine's rank-0 slice (v091 tp2r0, v070 ep2r0) and both runtime plans
under the served env; plans are invoked exactly as _apply_rank_sliced does (Engine.run_plan / run_decode_any /
run_apply).  Effects are kept separate, never combined:

  BASELINE (v091 only; the captured slice is tp2r0 rank 0): every captured entry through the plan the serving
      engine bound for (layer, m) (the moe_bind record), all m rows as served (padding included), twice; must be
      bit-equal to the captured served output (apply's return value) or the reason is reported.  Also through
      Exl3MoEMethod.apply (served dispatch).
  E-PLAN (within engine): decode plan vs prefill plan on the captured rows (real rows compared), 2 repeats each;
      per-row bit equality, rel L2, max abs; m <= 8 rows are expected equal (same tile).
  COMPOSED m = 40 / 48: real rows of two traffic-phase captures concatenated (a batch composition 0.9.1 does not
      serve at 8 in flight); prefill(m) vs decode in <= 32-row chunks.  Labelled "composed".
  CONTROL: +1 bf16 ulp on one row's largest channel changes exactly that row in both plans.
  FORCED-TILE CONFIRMATION (v091, --forced-tile; coordinator's check after SOURCE-MECHANISM.md): a second copy of
      each captured layer is built through the same image code path with the weight plan's tile forced to
      (64, 256, 64, 256) -- exl3._prepare_projection_mixed_weights calls api.plan_weights(trellis_tile_config=
      tile_config) with tile_config = None (exl3.py:2480); for the forced copy the api object returned by
      exl3._load_b12x_fused_moe is a proxy whose plan_weights substitutes (64, 256, 64, 256) for that None, and
      layer.exl3_trellis_tile_config is set to the same tuple afterwards (what a non-None tile_config at :2480
      would also set; it is part of the runtime cache key).  Its decode runtime is planned by
      _rank_sliced_runtime under the served env with VLLM_EXL3_PREFILL_TRELLIS=0 (no second prefill arena).  The
      bound decode launch must show fc1/fc2 K64/N256 at m = 16..32 (else "forcing not effective").  Prediction:
      forced decode == stock prefill plan, bit for bit, on the captured m = 16..32 rows and on the P3 synthetic
      m = 16 / 32 fixtures (x1, uniform, 3 concentrations, seed 0; inputs regenerated by moe_plan_eq.make_fixture,
      digests checked against P3's v091.json).  Recorded as its own section, never mixed with E-PLAN.

Public OUT.json: counts, flags, launch maps, magnitudes, digests; no tensors.
--dry: CPU only.  Plan outputs come from moe_plan_eq.dry_kernel (row-local, plan difference injected at m > 16);
fabricated captures carry dry_kernel "served" outputs so BASELINE passes except on injected rows.
--dry-forced-probe: also runs the forced-tile weight-plan path on CPU through the image code up to
api.prepare_weights (needs the model snapshot) and the image's _projection_mixed_tile_config rule.
"""
