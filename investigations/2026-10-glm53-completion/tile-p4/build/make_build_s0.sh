#!/bin/bash
# GENERATED from make_build.sh by hand for STAGE 0 (2026-10-24): same gates, outputs under build/stage0/, tag
# local/glm53-v091-p4-s0:local (p4_hooks schema 2 + stage-0 recording; forcewin port P14-P16 multi-prompt).
# Builds the image from the LOCAL stock 0.9.1 image (a9e985c0), CPU only:
# `docker build --network none --pull=false`; every check container is `docker run --rm --network none` with
# CUDA_VISIBLE_DEVICES= (no --gpus).  Never retags or removes any existing image; refuses if the tag exists.
#   1. make_hooked.py --check and port_forcewin.py --check (regenerated == on disk; additive gate; forcewin call
#      sites == the validated attempt-2 copies; stock-equivalence after removing the marked lines)
#   2. $O/Dockerfile.s0 generated (kept as a record); in-build gates: stock hashes before COPY, reviewed hashes after,
#      py_compile, marker counts, both modules inert without their env
#   3. post-build gates ($O/post-build-gates.txt): (a) of all vllm/*.py only the 7 expected files differ from stock;
#      (b1) env unset: every hook flag False, _p4_forced_tile() is None, nothing patched;
#      (b2) GLM53_P4_TILE: exactly "64,256,64,256" -> (64, 256, 64, 256); anything else -> None;
#      (b3) GLM53_P4=on + FORCEWIN=on: hooks on, bridge on, no device state before registration;
#      (c) image layers extend the base layers.
# Output: $O/build-s0.log, $O/image-id.txt, $O/image-vllm-py.sha256, $O/stock-vllm-py.sha256, $O/post-build-gates.txt
set -u
cd "$(dirname "$0")" || exit 2
BASE=ghcr.io/tpurtell/glm-5.3-flash-exl3-4bpw-2x-rtx@sha256:a9e985c09885710601b32ac86e81256aa1279b542caa345233ce331a816d7e07
TAG=${P4_TAG:-local/glm53-v091-p4-s0:local}
O=stage0
VP=/usr/local/lib/python3.12/dist-packages/vllm
case "$TAG" in local/glm53-v091-p4-*:local) ;; *) echo "REFUSED: tag outside local/glm53-v091-p4-*:local"; exit 2;; esac
docker image inspect "$TAG" >/dev/null 2>&1 && { echo "REFUSED: $TAG exists (new tags only; never retagged)"; exit 2; }
docker image inspect "$BASE" >/dev/null 2>&1 || { echo "ABORT: base image missing locally (no pulls)"; exit 3; }
python3 make_hooked.py --check || { echo "ABORT: hooked files fail their gates"; exit 4; }
python3 port_forcewin.py --check || { echo "ABORT: forcewin port does not regenerate"; exit 4; }
rm -rf files/vllm/__pycache__

F_FW="v1/worker/gpu/model_runner.py v1/worker/gpu/spec_decode/rejection_sampler.py v1/worker/gpu/sample/sampler.py"
F_P4="model_executor/layers/quantization/exl3.py models/glm5next/nvidia/model.py"
H() { sha256sum "files/vllm/$1" | cut -d' ' -f1; }
{
echo "# GENERATED by make_build.sh (do not edit): stock tpurtell 0.9.1 + local-forcewin (stock port) + local-p4."
echo "# Inert unless FORCEWIN=on / GLM53_P4=on; arm B only with GLM53_P4_TILE=64,256,64,256."
echo "FROM ${BASE}"
echo "ARG VP=${VP}"
echo "# Gate 0: the replaced files are the stock 0.9.1 files; no local hook module present."
echo "RUN printf '%s\\n' \\"
for f in $F_FW $F_P4; do echo "    \"$(sha256sum "stock/$f" | cut -d' ' -f1)  \${VP}/$f\" \\"; done
echo "  | sha256sum -c - && ! test -e \${VP}/p4_hooks.py && ! test -e \${VP}/forcewin_hooks.py"
echo "COPY files/vllm/p4_hooks.py \${VP}/p4_hooks.py"
echo "COPY files/vllm/forcewin_hooks.py \${VP}/forcewin_hooks.py"
for f in $F_FW $F_P4; do echo "COPY files/vllm/$f \${VP}/$f"; done
echo "RUN printf '%s\\n' \\"
for f in p4_hooks.py forcewin_hooks.py $F_FW $F_P4; do echo "    \"$(H $f)  \${VP}/$f\" \\"; done
echo "  | sha256sum -c - \\"
echo " && python3 -m py_compile \${VP}/p4_hooks.py \${VP}/forcewin_hooks.py $(for f in $F_FW $F_P4; do printf '${VP}/%s ' $f; done) \\"
for f in $F_FW; do echo " && test \"\$(grep -c local-forcewin \${VP}/$f)\" = $(grep -c local-forcewin files/vllm/$f) \\"; done
for f in $F_P4; do echo " && test \"\$(grep -c local-p4 \${VP}/$f)\" = $(grep -c local-p4 files/vllm/$f) \\"; done
echo " && CUDA_VISIBLE_DEVICES= python3 -c \"import importlib.util as u; s=u.spec_from_file_location('m','\${VP}/p4_hooks.py'); m=u.module_from_spec(s); s.loader.exec_module(m); assert not m.ENABLED\""
echo "LABEL io.local.base=\"stock tpurtell 0.9.1 sha256:a9e985c0\" io.local.purpose=\"P4 stage 0: forcewin (stock port, multi-prompt) + local-p4 schema 2 + stage-0 recording (GLM53_P4_S0); inert unless FORCEWIN/GLM53_P4 set; arm B via GLM53_P4_TILE\""
} > $O/Dockerfile.s0

docker build --network none --pull=false -f $O/Dockerfile.s0 -t "$TAG" . > $O/build-s0.log 2>&1
rc=$?; echo "build rc=$rc"
[ $rc = 0 ] || { tail -20 $O/build-s0.log; exit 5; }
docker image inspect "$TAG" --format '{{.Id}}' > $O/image-id.txt && cat $O/image-id.txt

{
  echo "== post-build gates $(date -u +%FT%TZ) image $(cat $O/image-id.txt)"
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= --entrypoint sh "$TAG" -c "cd $VP && find . -name '*.py' | sort | xargs sha256sum" > $O/image-vllm-py.sha256
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= --entrypoint sh "$BASE" -c "cd $VP && find . -name '*.py' | sort | xargs sha256sum" > $O/stock-vllm-py.sha256
  echo "vllm .py files: image $(wc -l < $O/image-vllm-py.sha256), stock $(wc -l < $O/stock-vllm-py.sha256)"
  DIFF=$(diff <(sort -k2 $O/stock-vllm-py.sha256) <(sort -k2 $O/image-vllm-py.sha256) | grep '^[<>]' | awk '{print $3}' | sort -u | tr '\n' ' ')
  echo "files differing from stock: $DIFF"
  EXP="./forcewin_hooks.py ./p4_hooks.py ./model_executor/layers/quantization/exl3.py ./models/glm5next/nvidia/model.py ./v1/worker/gpu/model_runner.py ./v1/worker/gpu/sample/sampler.py ./v1/worker/gpu/spec_decode/rejection_sampler.py "
  if [ "$DIFF" = "$EXP" ]; then echo "PASS gate (a): only the 7 expected files differ"; else echo "FAIL gate (a): expected $EXP"; fi
  for f in p4_hooks.py forcewin_hooks.py $F_FW $F_P4; do
    IH=$(grep " \./$f\$" $O/image-vllm-py.sha256 | cut -d' ' -f1)
    [ "$IH" = "$(H $f)" ] && echo "PASS installed $f == reviewed" || echo "FAIL installed $f differs from build/files"
  done
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= --entrypoint python3 "$TAG" -c "
import vllm.p4_hooks as p4, vllm.forcewin_hooks as fw
import vllm.model_executor.layers.quantization.exl3 as e
import vllm.models.glm5next.nvidia.model as gm
import vllm.v1.worker.gpu.model_runner as mr, vllm.v1.worker.gpu.sample.sampler as sa
import vllm.v1.worker.gpu.spec_decode.rejection_sampler as rs, vllm.v1.worker.gpu.cudagraph_utils as cg
assert not p4.ENABLED and not fw.ON and fw._p4b is None
assert not e._P4_ON and not gm._P4_ON and not mr._FW_ON and not sa._FW_ON and not rs._FW_ON
assert e._p4_forced_tile() is None
assert not getattr(cg.CudaGraphManager, '_p4_hooks', False)
assert p4.S.stage is None and fw.S.dev is None
print('PASS gate (b1): env unset -> all hook flags False, _p4_forced_tile() is None, nothing patched or allocated')
" 2>&1 | grep -E "^(PASS|FAIL)|Traceback|^[A-Za-z]*Error"
  for v in "64,256,64,256" "64,256,64,256 " "64,256" "128,128,128,128" "1"; do
    docker run --rm --network none -e CUDA_VISIBLE_DEVICES= -e "GLM53_P4_TILE=$v" --entrypoint python3 "$TAG" -c "
import os, vllm.model_executor.layers.quantization.exl3 as e
v = os.environ['GLM53_P4_TILE']; t = e._p4_forced_tile()
exp = (64, 256, 64, 256) if v == '64,256,64,256' else None
print(('PASS' if t == exp else 'FAIL') + ' gate (b2): GLM53_P4_TILE=%r -> %r (P4 hooks %s)' % (v, t, e._P4_ON))
" 2>&1 | grep -E "^(PASS|FAIL)|Traceback|^[A-Za-z]*Error"
  done
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= -e GLM53_P4=on -e FORCEWIN=on -e GLM53_P4_DIR=/tmp/p4 --entrypoint python3 "$TAG" -c "
import vllm.p4_hooks as p4, vllm.forcewin_hooks as fw
import vllm.model_executor.layers.quantization.exl3 as e
import vllm.models.glm5next.nvidia.model as gm
import vllm.v1.worker.gpu.model_runner as mr
assert p4.ENABLED and fw.ON and fw._p4b is p4 and e._P4_ON and gm._P4_ON and mr._FW_ON
assert e._p4_forced_tile() is None
assert p4.S.stage is None and fw.S.dev is None and not p4.S.registered
assert not fw.D2_ALLOWED and not fw.SHADOW and not fw.SNAP and fw.DRAFT_MODES['list'] == 5
print('PASS gate (b3): GLM53_P4=on FORCEWIN=on -> hooks and bridge on; no device state before registration; B1-only features off')
" 2>&1 | grep -E "^(PASS|FAIL)|Traceback|^[A-Za-z]*Error"
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= -e GLM53_P4=on -e GLM53_P4_S0=on -e FORCEWIN=on --entrypoint python3 "$TAG" -c "
import vllm.p4_hooks as p4, vllm.forcewin_hooks as fw
assert p4.S0 and p4.SCHEMA == 'local-p4/2' and p4.STEPREC_COLS[-2:] == ('uid', 'taghash') and fw._p4b is p4
assert p4.S.ldig is None and p4.S.edig is None and not p4.S.eready
import json
assert fw.multi_pick(json.dumps(dict(entries=[dict(key=fw.multi_key([1, 2, 3]), F=[5], tag='t')])), [1, 2, 3]) == ([5], 't')
print('PASS gate (b4): GLM53_P4=on GLM53_P4_S0=on -> stage-0 recording on (schema 2, uid columns), nothing allocated before registration; multi-prompt pick')
" 2>&1 | grep -E "^(PASS|FAIL)|Traceback|^[A-Za-z]*Error"
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= -e GLM53_P4_S0=on --entrypoint python3 "$TAG" -c "
import vllm.p4_hooks as p4
assert not p4.ENABLED and not p4.S0
print('PASS gate (b5): GLM53_P4_S0=on alone (GLM53_P4 unset) -> everything off')
" 2>&1 | grep -E "^(PASS|FAIL)|Traceback|^[A-Za-z]*Error"
  python3 - "$BASE" "$TAG" <<'PY'
import json, subprocess, sys
L = lambda i: json.loads(subprocess.check_output(["docker", "image", "inspect", i, "--format", "{{json .RootFS.Layers}}"]))
b, d = L(sys.argv[1]), L(sys.argv[2])
print(("PASS" if d[:len(b)] == b and len(d) > len(b) else "FAIL") + " gate (c): image layers extend the base (%d -> %d)" % (len(b), len(d)))
PY
} 2>&1 | tee $O/post-build-gates.txt
grep -qE "^FAIL|Traceback|^[A-Za-z]*Error" $O/post-build-gates.txt && exit 6
exit 0
