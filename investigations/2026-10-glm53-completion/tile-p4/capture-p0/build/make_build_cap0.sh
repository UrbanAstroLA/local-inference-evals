#!/bin/bash
# Builds local/glm53-v091-p4-cap0:local FROM the stage-0 image local/glm53-v091-p4-s0:local (sha256:7408f893...),
# CPU only: `docker build --network none --pull=false`; every check container is `docker run --rm --network none`
# with CUDA_VISIBLE_DEVICES= (no --gpus).  Never retags or removes an image; refuses if the tag exists.
#   0. base image id == the stage-0 pin; p4_hooks.py minus its "# local-cap0" lines == the stage-0 module
#   1. Dockerfile.cap0 generated (kept as a record); in-build gates: base p4_hooks.py hash before COPY, reviewed
#      hashes after, py_compile, marker count, switch off -> cap0_hooks not imported, switch on -> imported, inert
#   2. post-build gates (post-build-gates.txt): (a) of all vllm/*.py only p4_hooks.py differs from the stage-0
#      image and the two new modules are added; (b1) env unset: stage-0 gate b1 holds and nothing cap0 is imported;
#      (b2) GLM53_P4=on GLM53_P4_S0=on, GLM53_CAP0 unset: the stage-0 module state, cap0 not imported;
#      (b3) GLM53_CAP0=on without GLM53_P4_S0: not imported; (b4) all on (+LOC): imported, nothing registered,
#      no hooks, the conv patch target kda.causal_conv1d_fn exists; (c) image layers extend the base layers.
# Output: build-cap0.log, image-id.txt, image-vllm-py.sha256, base-vllm-py.sha256, post-build-gates.txt
set -u
cd "$(dirname "$0")" || exit 2
BASE=local/glm53-v091-p4-s0:local
BASE_ID=sha256:7408f893dfe35f1fbd330153e34ea81e83460fe5e2fff200ab87ea992565d3c7
BASE_P4_SHA=93f4147a49caf2e2ddc6bbaf269d53fc29095d1a69953a9e923b552241d1ff6d
TAG=${CAP0_TAG:-local/glm53-v091-p4-cap0-a2:local}   # attempt 2; the attempt-1 image keeps local/glm53-v091-p4-cap0:local (build/attempt1/)
VP=/usr/local/lib/python3.12/dist-packages/vllm
case "$TAG" in local/glm53-v091-p4-*:local) ;; *) echo "REFUSED: tag outside local/glm53-v091-p4-*:local"; exit 2;; esac
GATES_ONLY=${GATES_ONLY:-0}     # 1: re-run only the post-build gates on the already built tag (its id must be image-id.txt)
if [ "$GATES_ONLY" = 1 ]; then
  [ "$(docker image inspect "$TAG" --format '{{.Id}}' 2>/dev/null)" = "$(cat image-id.txt 2>/dev/null)" ] || { echo "REFUSED: GATES_ONLY needs $TAG == image-id.txt"; exit 2; }
else
  docker image inspect "$TAG" >/dev/null 2>&1 && { echo "REFUSED: $TAG exists (new tags only; never retagged)"; exit 2; }
fi
[ "$(docker image inspect "$BASE" --format '{{.Id}}' 2>/dev/null)" = "$BASE_ID" ] || { echo "ABORT: $BASE is not $BASE_ID"; exit 3; }
S0P4=../../build/files/vllm/p4_hooks.py
[ "$(sha256sum "$S0P4" | cut -d' ' -f1)" = "$BASE_P4_SHA" ] || { echo "ABORT: stage-0 p4_hooks.py on disk is not the served copy"; exit 3; }
python3 - "$S0P4" files/vllm/p4_hooks.py <<'PY' || { echo "ABORT: p4_hooks.py is not the stage-0 module plus marked lines"; exit 4; }
import sys
a, b = open(sys.argv[1]).read(), open(sys.argv[2]).read()
M = "  # local-cap0"
kept = "".join(l for l in b.splitlines(True) if not l.rstrip("\n").endswith(M))
n = sum(1 for l in b.splitlines() if l.endswith(M))
print(("PASS" if kept == a else "FAIL") + " gate 0: p4_hooks.py minus its %d marked lines == the stage-0 module" % n)
sys.exit(0 if kept == a else 1)
PY
rm -rf files/vllm/__pycache__
H() { sha256sum "files/vllm/$1" | cut -d' ' -f1; }
NMARK=$(grep -c '# local-cap0$' files/vllm/p4_hooks.py)
{
echo "# GENERATED by make_build_cap0.sh (do not edit): the stage-0 image + local-cap0 (point-0 capture, localisation)."
echo "# Inert unless GLM53_P4=on GLM53_P4_S0=on GLM53_CAP0=on; with GLM53_CAP0 unset cap0_hooks is never imported."
echo "FROM ${BASE}"
echo "ARG VP=${VP}"
echo "RUN printf '%s\\n' \"${BASE_P4_SHA}  \${VP}/p4_hooks.py\" | sha256sum -c - \\"
echo " && ! test -e \${VP}/cap0_hooks.py && ! test -e \${VP}/cap0_hooks_layout.py"
for f in p4_hooks.py cap0_hooks.py cap0_hooks_layout.py; do echo "COPY files/vllm/$f \${VP}/$f"; done
echo "RUN printf '%s\\n' \\"
for f in p4_hooks.py cap0_hooks.py cap0_hooks_layout.py; do echo "    \"$(H $f)  \${VP}/$f\" \\"; done
echo "  | sha256sum -c - \\"
echo " && python3 -m py_compile \${VP}/p4_hooks.py \${VP}/cap0_hooks.py \${VP}/cap0_hooks_layout.py \\"
echo " && test \"\$(grep -c '# local-cap0\$' \${VP}/p4_hooks.py)\" = $NMARK \\"
echo " && CUDA_VISIBLE_DEVICES= GLM53_P4=on GLM53_P4_S0=on python3 -c \"import sys, vllm.p4_hooks as p; assert p._cap0 is None and 'vllm.cap0_hooks' not in sys.modules\" \\"
echo " && CUDA_VISIBLE_DEVICES= GLM53_P4=on GLM53_P4_S0=on GLM53_CAP0=on python3 -c \"import vllm.p4_hooks as p; assert p._cap0 is not None and p._cap0.ON and not p._cap0.LOC and not p._cap0.S.registered\""
echo "LABEL io.local.base=\"local/glm53-v091-p4-s0:local ${BASE_ID}\" io.local.purpose=\"P4 capture-p0: stage-0 image + local-cap0 point-0 byte capture and warm-prefill localisation; inert unless GLM53_CAP0=on\""
} > Dockerfile.cap0

if [ "$GATES_ONLY" != 1 ]; then
  docker build --network none --pull=false -f Dockerfile.cap0 -t "$TAG" . > build-cap0.log 2>&1
  rc=$?; echo "build rc=$rc"
  [ $rc = 0 ] || { tail -20 build-cap0.log; exit 5; }
  docker image inspect "$TAG" --format '{{.Id}}' > image-id.txt && cat image-id.txt
fi
IMG=$(cat image-id.txt)
{
  echo "== post-build gates $(date -u +%FT%TZ) image $IMG"
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= --entrypoint sh "$IMG" -c "cd $VP && find . -name '*.py' | sort | xargs sha256sum" > image-vllm-py.sha256
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= --entrypoint sh "$BASE_ID" -c "cd $VP && find . -name '*.py' | sort | xargs sha256sum" > base-vllm-py.sha256
  echo "vllm .py files: image $(wc -l < image-vllm-py.sha256), stage-0 base $(wc -l < base-vllm-py.sha256)"
  DIFF=$(diff <(LC_ALL=C sort -k2 base-vllm-py.sha256) <(LC_ALL=C sort -k2 image-vllm-py.sha256) | grep '^[<>]' | awk '{print $3}' | LC_ALL=C sort -u | tr '\n' ' ')
  echo "files differing from the stage-0 image: $DIFF"
  EXP="./cap0_hooks.py ./cap0_hooks_layout.py ./p4_hooks.py "
  if [ "$DIFF" = "$EXP" ]; then echo "PASS gate (a): only p4_hooks.py differs and the two cap0 modules are added"; else echo "FAIL gate (a): expected $EXP"; fi
  for f in p4_hooks.py cap0_hooks.py cap0_hooks_layout.py; do
    IH=$(grep " \./$f\$" image-vllm-py.sha256 | cut -d' ' -f1)
    [ "$IH" = "$(H $f)" ] && echo "PASS installed $f == reviewed" || echo "FAIL installed $f differs from build/files"
  done
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= --entrypoint python3 "$IMG" -c "
import sys
import vllm.p4_hooks as p4, vllm.forcewin_hooks as fw
import vllm.model_executor.layers.quantization.exl3 as e
import vllm.models.glm5next.nvidia.model as gm
import vllm.v1.worker.gpu.model_runner as mr, vllm.v1.worker.gpu.sample.sampler as sa
import vllm.v1.worker.gpu.spec_decode.rejection_sampler as rs, vllm.v1.worker.gpu.cudagraph_utils as cg
assert not p4.ENABLED and not fw.ON and fw._p4b is None
assert not e._P4_ON and not gm._P4_ON and not mr._FW_ON and not sa._FW_ON and not rs._FW_ON
assert e._p4_forced_tile() is None
assert not getattr(cg.CudaGraphManager, '_p4_hooks', False)
assert p4.S.stage is None and fw.S.dev is None
assert p4._cap0 is None and 'vllm.cap0_hooks' not in sys.modules
print('PASS gate (b1): env unset -> stage-0 gate b1 holds; cap0_hooks not imported')
" 2>&1 | grep -E "^(PASS|FAIL)|Traceback|^[A-Za-z]*Error"
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= -e GLM53_P4=on -e GLM53_P4_S0=on -e FORCEWIN=on --entrypoint python3 "$IMG" -c "
import sys, json
import vllm.p4_hooks as p4, vllm.forcewin_hooks as fw
assert p4.S0 and p4.SCHEMA == 'local-p4/2' and p4.STEPREC_COLS[-2:] == ('uid', 'taghash') and fw._p4b is p4
assert p4.S.ldig is None and p4.S.edig is None and not p4.S.eready
assert fw.multi_pick(json.dumps(dict(entries=[dict(key=fw.multi_key([1, 2, 3]), F=[5], tag='t')])), [1, 2, 3]) == ([5], 't')
assert p4._cap0 is None and p4._CAP0_ERR is None and 'vllm.cap0_hooks' not in sys.modules
print('PASS gate (b2): GLM53_P4=on GLM53_P4_S0=on, GLM53_CAP0 unset -> stage-0 gate b4 holds; cap0_hooks not imported')
" 2>&1 | grep -E "^(PASS|FAIL)|Traceback|^[A-Za-z]*Error"
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= -e GLM53_P4=on -e GLM53_CAP0=on --entrypoint python3 "$IMG" -c "
import sys, vllm.p4_hooks as p4
assert not p4.S0 and p4._cap0 is None and 'vllm.cap0_hooks' not in sys.modules
print('PASS gate (b3): GLM53_CAP0=on without GLM53_P4_S0 -> not imported')
" 2>&1 | grep -E "^(PASS|FAIL)|Traceback|^[A-Za-z]*Error"
  docker run --rm --network none -e CUDA_VISIBLE_DEVICES= -e GLM53_P4=on -e GLM53_P4_S0=on -e GLM53_CAP0=on -e GLM53_CAP0_LOC=on -e FORCEWIN=on --entrypoint python3 "$IMG" -c "
import vllm.p4_hooks as p4
c = p4._cap0
assert c is not None and c.ON and c.LOC and c.LOC_TOKENS == 13056 and not c.S.registered and not c.S.hooks and not c.S.conv_patched
from vllm.models.glm5next.nvidia import kda
assert callable(kda.causal_conv1d_fn) and not hasattr(kda.causal_conv1d_fn, '_cap0_hooks_orig')
print('PASS gate (b4): GLM53_CAP0=on GLM53_CAP0_LOC=on -> imported and on; nothing registered, no hooks; conv patch target present and unpatched')
" 2>&1 | grep -E "^(PASS|FAIL)|Traceback|^[A-Za-z]*Error"
  python3 - "$BASE_ID" "$IMG" <<'PY'
import json, subprocess, sys
L = lambda i: json.loads(subprocess.check_output(["docker", "image", "inspect", i, "--format", "{{json .RootFS.Layers}}"]))
b, d = L(sys.argv[1]), L(sys.argv[2])
print(("PASS" if d[:len(b)] == b and len(d) > len(b) else "FAIL") + " gate (c): image layers extend the stage-0 base (%d -> %d)" % (len(b), len(d)))
PY
} 2>&1 | tee post-build-gates.txt
grep -qE "^FAIL|Traceback|^[A-Za-z]*Error" post-build-gates.txt && exit 6
exit 0
